//*****************************************************************************
// 更新
//*****************************************************************************
void PlayerUpdate()
{
	//playerが作られていなければ何もしない
	if (!g_player)
	{
		return;
	}

	//中身を取り出す
	Player& player = *g_player;
	//クールタイムを１フレーム分減らす
	player.SetDashCDTimer((std::max)(0.0f, player.GetDashCDTimer() - FRAME_TIME));

	//状態ごとに呼ぶ関数を切り替える
	switch (player.GetState())
	{
	case Player::IDLE:
		PlayerIdle(player);
		break;

	case Player::MOVE:
		PlayerMove(player);
		break;

	case Player::JUMP:
		PlayerJump(player);
		break;

	case Player::DASH:
		PlayerDash(player);
		break;
	}

}

